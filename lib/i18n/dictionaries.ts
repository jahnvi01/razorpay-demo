export const dictionaries: Record<Lang, Dictionary> = { en, hi };

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}


/** Keys ending in ".one" are the singular form, used automatically when vars.count is 1. */
export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => {
    const singular = `${key}.one` as MessageKey;
    const text = vars?.count === 1 && singular in dict ? dict[singular] : dict[key];
    return vars ? text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`)) : text;
  };
}
